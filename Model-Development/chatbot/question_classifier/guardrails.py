"""Medical-advice guardrails around the question classifier.

Strict rule: the chatbot never gives medical advice and never judges whether a device is
safe. A model alone cannot guarantee that, so out_of_scope is decided in layers:

  1. Rule backstop (this file): fixed patterns mark a question out_of_scope even when the
     model does not. They fire only when the user asks the bot to judge or advise, not on a
     trigger word alone ("dangerous malfunctions reported", "dosing errors").
  2. Classifier: out_of_scope threshold set for high recall on validation (train.py).
  3. Routing (route()): with the default "facts_with_refusal" policy the advice part gets
     REFUSAL, fixed text written here, never generated by a model, and the factual queries
     still run. With "strict" no query runs.
  4. The chatbot's output gate (teammate's design) blocks advice wording in drafts.

FROZEN: rules_fingerprint() is recorded with every model and evaluation. The held-out split
was scored after the rules were frozen; changing a pattern makes those numbers stale.
"""
from __future__ import annotations

import hashlib
import re

from .labels import OUT_OF_SCOPE

REFUSAL = (
    "I can't give medical advice or judge whether a device is safe for you. "
    "Please talk to your doctor or another qualified health professional about your "
    "situation. If you think a device has harmed someone, you can report it to the FDA "
    "through MedWatch. I can share what FDA reports and recalls say about a device, for "
    "example how many reports it has or whether it has been recalled."
)

# Each pattern is matched against the lower-cased question.
_JUDGE = r"(?:safe|unsafe|dangerous|risky|harmful|reliable|ok|okay)"
_BOT = r"(?:this|the) (?:bot|chatbot|tool|site|app|database|search)"
_NOT_A_CHOICE = r"(?!\s+(?:way|ways|time|place|method|practice|source|resource)s?\b)"
_RELATIVE = r"(?:son|daughter|mom|dad|mother|father|wife|husband|child|kid|baby|partner)"
_SYMPTOM = (r"(?:pain|rash|fever|infection|bleeding|swelling|headache|dizz\w*|numb\w*|redness|"
            r"burn\w*|nause\w*|symptoms?|shortness of breath|itch\w*)")

ADVICE_PATTERNS: tuple[tuple[str, str], ...] = (
    # "should I/we/my mom…", but not questions about using the bot ("should I search…")
    ("should_i",         r"\bshould (?:i|we|my|he|she|they|you)\b(?!\s+(?:search|look|type|enter|"
                         r"ask|filter|query|use " + _BOT + r"))"),
    ("what_to_do",       r"\bwhat (?:do|should|can) (?:i|we) do\b(?!\s+with " + _BOT + r")"),
    # "is/are X safe", "is X a dangerous device" - not "are there dangerous malfunctions"
    ("safety_judgement", r"\b(?:is|are|was|were)\s+(?!there\b)(?:[\w:.'/-]+\s+){0,6}?(?:a |an )?"
                         + _JUDGE + r"(?:\s+(?:device|devices|choice|option|product|implant|pump|"
                         r"one|enough|anymore|now|still))?\s*(?:$|[?.!,;]|\b(?:to|for|or|and|if|"
                         r"after|with)\b)"),
    ("safe_to",          r"\bsafe (?:to|for)\b"),
    ("comparison",       r"\b(?:safer|better|more reliable|riskier|worse) than\b"),
    # "best X on the market / for me", "which is safest" - not "best way to report"
    ("best_choice",      r"\b(?:best|safest|safer|better|most reliable)\b" + _NOT_A_CHOICE +
                         r".{0,40}\b(?:on the market|to (?:buy|use|get|choose|pick)|for (?:me|my|"
                         r"a patient|patients|kids|children|our))\b"
                         r"|\b(?:which|what)(?:'s|(?:\s+[\w:.'-]+){0,3}\s+(?:is|are))\s+(?:the\s+)?"
                         r"(?:best|safest|safer|better|most reliable)\b" + _NOT_A_CHOICE),
    # first person only: "should I stop", "I want to switch", "stop using my" - not "replace my"
    ("stop_switch",      r"\b(?:should|can|do|must|could) (?:i|we)(?: still| just)? (?:stop|keep|"
                         r"start|continue|switch|quit|remove|change)\b"
                         r"|\bi(?:'m| am)? (?:want|need|plan|going|thinking about|considering)"
                         r"(?: to)? (?:stop|quit|switch|remov|replac)\w*\b"
                         r"|\b(?:stop|quit|keep) (?:using|wearing|taking) (?:my|our|it)\b"),
    # "how much insulin", "how many units … insulin / should I take" - not "units recalled"
    ("dosing",           r"\bhow (?:much|many units of) insulin\b"
                         r"|\bhow many units\b.*\b(?:insulin|should i take|do i take)\b"
                         r"|\b(?:what|which) (?:dose|dosage) (?:should|do) (?:i|we|he|she)\b"
                         r"|\bhow much (?:should|do) (?:i|we) (?:take|use|give)\b"),
    # first person only: "I have a rash", "my dad has swelling", "my symptoms"
    ("symptoms",         r"\b(?:i|my " + _RELATIVE + r")(?:'ve| have| has| had| am having| is having|"
                         r" feel| feels| got| developed| noticed)\b.{0,40}\b" + _SYMPTOM + r"\b"
                         r"|\bmy " + _SYMPTOM + r"\b"),
    # asking the bot for a recommendation - not "what did the recall recommend"
    ("recommend",        r"\b(?:do|would|can|could) you (?:recommend|suggest|advise)\b"
                         r"|\brecommend (?:me|a|an|which|the best)\b|\bmedical advice\b"
                         r"|\b(?:your|any) advice\b"),
    ("can_i",            r"\bcan i (?:still |keep |safely )?(?:use|wear|take)\b(?!\s+" + _BOT + r")"),
)
_COMPILED = tuple((name, re.compile(pat)) for name, pat in ADVICE_PATTERNS)

POLICIES = ("strict", "facts_with_refusal")
DEFAULT_POLICY = "facts_with_refusal"


def rules_fingerprint() -> str:
    """Short hash of the patterns (see FROZEN above)."""
    text = "\n".join(f"{n}={p}" for n, p in ADVICE_PATTERNS)
    return hashlib.sha256(text.encode()).hexdigest()[:12]


def rule_hits(question: str) -> list[str]:
    """Names of the advice patterns that match the question."""
    q = question.lower()
    return [name for name, rx in _COMPILED if rx.search(q)]


def route(labels: list[str], question: str, policy: str = DEFAULT_POLICY) -> dict:
    """Combine model labels with the rule backstop and decide what the chatbot does.

    Returns {"labels", "rule_hits", "out_of_scope", "run_queries", "refusal"}:
      strict              out_of_scope → refuse, run no query
      facts_with_refusal  (default) out_of_scope → refuse the advice part, still run the factual
                          labels' queries (the answer must start with REFUSAL)
    No label at all (low confidence) → run nothing, ask the user to rephrase.
    """
    if policy not in POLICIES:
        raise ValueError(f"policy must be one of {POLICIES}")
    hits = rule_hits(question)
    final = sorted(set(labels) | ({OUT_OF_SCOPE} if hits else set()))
    oos = OUT_OF_SCOPE in final
    factual = [lbl for lbl in final if lbl != OUT_OF_SCOPE]
    if oos and policy == "strict":
        run = []
    else:
        run = factual
    return {"labels": final, "rule_hits": hits, "out_of_scope": oos,
            "run_queries": run, "refusal": REFUSAL if oos else None}
