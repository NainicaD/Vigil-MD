"""Medical-advice guardrails inside the query router.

Strict rule: the chatbot never gives medical advice and never judges whether a device is
safe. A model alone cannot guarantee that, so out_of_scope is decided in layers:

  1. Rule backstop (this file): fixed patterns mark a question out_of_scope even when the
     model does not. They fire only when the user asks the bot to judge or advise, not on a
     trigger word alone ("dangerous malfunctions reported", "dosing errors").
  2. Classifier: out_of_scope threshold set for high recall on validation (train.py).
  3. Routing (route()): with the default "facts_with_refusal" policy the advice part gets
     REFUSAL, fixed text written here, never generated by a model, and the factual queries
     still run. With "strict" no query runs.
  4. The chatbot's output gate (teammate's design) blocks advice wording in drafts.

FROZEN: rules_fingerprint() is recorded with every model and evaluation. Revision 2
(cf0ad77c93da, 2026-11-08) added "opinion" and "urgent", using held-out misses. Revision 3
(6705cf050941, 2026-11-09) added "decision" and "own_device", extended "opinion",
"comparison", "best_choice", "can_i" and "safety_judgement", and narrowed "safe_to",
"dosing" and "safety_judgement" for the three false-alarm-set hits, using the misses of
handwritten_test.jsonl: that set is a development set now. The honest score is
handwritten_test_v2.jsonl, written by teammates after this freeze and scored once. Changing a
pattern makes it stale too. Revision 4 (5d1584bb53b3, 2026-11-11) adds "lump"/"lumps" to the
symptom words, from one handwritten_test_v2 miss ("I have Biocell implants and recently found a
lump near one") that the champion caught only by its model score: that one test row is no
longer an unbiased check of the rules.

Fixed replies (never model-written), chosen in route():
  help             "what can you do", "help", "who are you": what the bot answers, no query.
                   Only whole-question matches, and never when an advice rule fires.
  medical_refusal  out_of_scope with any sign of health or device context (an advice rule,
                   a factual label, a health/device word, or a word with a digit such as a
                   model number): REFUSAL.
  scope            out_of_scope with none of those signs (e.g. "write me a poem"): SCOPE_REPLY.
                   When in doubt it is medical_refusal, so safety never depends on this split.
These replies change only the text the user sees, not which questions are refused; the
advice patterns and their fingerprint are unchanged.
"""
