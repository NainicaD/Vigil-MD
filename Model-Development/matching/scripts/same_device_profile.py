"""Profile MAUDE and GUDID in BigQuery to back the "same device" definition.

Runs every sql/same_device/*.sql file (read-only, vigil_md_prod only), writes one CSV per
query part to reports/same_device/, and regenerates reports/same_device/RESULTS.md, which lists
each query, the check it does, and its result.

Every query is dry-run first. If any part is estimated above --max-gb, nothing
runs and the script exits 3. Each real job also sets maximum_bytes_billed.

Usage (from the repo root, in WSL):
  ~/.venvs/vigil-analysis/bin/python Model-Development/matching/scripts/same_device_profile.py \
      --project vigil-md-1792696816 --estimate-only
  ... --only 05 07          # run a subset by file prefix
  ... --print-only          # print rendered SQL, no GCP call
"""
from __future__ import annotations

import argparse
import csv
import datetime as dt
import json
import logging
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from vigil_model import bq_utils  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
SQL_DIR = ROOT / "sql" / "same_device"
OUT_DIR = ROOT / "reports" / "same_device"
EXIT_OK, EXIT_BAD_SQL, EXIT_OVER_BUDGET = 0, 2, 3
MD_ROW_CAP = 30

log = logging.getLogger("same_device_profile")


def rendered(files: list[bq_utils.QueryFile], project: str):
    """Yield (QueryFile, part name, final SQL), each checked read-only."""
    for qf in files:
        for part, sql in qf.parts:
            final = bq_utils.render(sql, project)
            bq_utils.assert_read_only(final)
            yield qf, part, final


def csv_name(qf: bq_utils.QueryFile, part: str) -> str:
    return f"{qf.qid}.csv" if part == "main" else f"{qf.qid}__{part}.csv"


def _cell(v):
    if isinstance(v, (list, dict, tuple)):
        return json.dumps(v, default=str)
    if isinstance(v, float):
        return f"{v:.6g}"
    return "" if v is None else str(v)


def write_csv(path: Path, rows: list[dict]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="", encoding="utf-8") as f:
        if not rows:
            f.write("")
            return
        w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        w.writeheader()
        for r in rows:
            w.writerow({k: _cell(v) for k, v in r.items()})


def _md_escape(s: str) -> str:
    return s.replace("|", "\\|").replace("\n", " ")


def md_table(rows: list[dict], cap: int = MD_ROW_CAP) -> str:
    if not rows:
        return "_(no rows)_\n"
    cols = list(rows[0].keys())
    out = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for r in rows[:cap]:
        cells = []
        for c in cols:
            v = _cell(r[c])
            cells.append(_md_escape(v if len(v) <= 120 else v[:117] + "..."))
        out.append("| " + " | ".join(cells) + " |")
    if len(rows) > cap:
        out.append(f"\n_{len(rows) - cap} more rows in the CSV._")
    return "\n".join(out) + "\n"


def build_results_md(files, results, bytes_by_part, project: str, run_at: str) -> str:
    lines = [
        "# Same-device data profile: results",
        "",
        f"Generated by `scripts/same_device_profile.py` on {run_at} against project `{project}`, "
        "dataset `vigil_md_prod` (read-only). Do not edit by hand; re-run the script.",
        "",
        "Each section is one file in `sql/same_device/`. *Check* is what the query measures; "
        "*Informs* is the same-device question it answers. Full results are in the CSVs next to this file.",
        "",
    ]
    for qf in files:
        h = qf.header
        lines += [f"## {qf.qid}: {h.get('Title', '')}", "",
                  f"- **Check:** {h.get('Check', '')}",
                  f"- **Why:** {h.get('Why', '')}",
                  f"- **Informs:** {h.get('Informs', '')}",
                  f"- **SQL:** [`sql/same_device/{qf.path.name}`](../../sql/same_device/{qf.path.name})", ""]
        for part, _ in qf.parts:
            key = (qf.qid, part)
            if key not in results:
                continue
            b = bytes_by_part.get(key) or {}
            n = b.get("processed") or b.get("estimated")
            scanned = f"{n / 1e9:.2f} GB scanned" if n else "scan size not recorded"
            title = "Result" if part == "main" else f"Part `{part}`"
            lines += [f"### {title} ([csv]({csv_name(qf, part)}), {len(results[key])} rows, "
                      f"{scanned})", "", md_table(results[key]), ""]
    return "\n".join(lines)


def estimate_all(client, items, max_gb: float):
    """Dry-run every part. Returns (estimates, over budget, failed to compile)."""
    estimates, failed = {}, {}
    for qf, part, sql in items:
        key = (qf.qid, part)
        try:
            estimates[key] = bq_utils.estimate_bytes(client, sql)
        except Exception as e:   # report every broken query, not just the first
            failed[key] = getattr(e, "message", None) or str(e)
            log.error("FAIL %s/%s: %s", qf.qid, part, failed[key])
            continue
        log.info("estimate %s/%s: %.3f GB", qf.qid, part, estimates[key] / 1e9)
    over = {k: b for k, b in estimates.items() if b / 1e9 > max_gb}
    for (q, p), b in over.items():
        log.error("STOP %s/%s: %.3f GB is above --max-gb %.1f", q, p, b / 1e9, max_gb)
    return estimates, over, failed


def run(client, project: str, files, out: Path, max_gb: float,
        estimate_only: bool = False, sql_dir: Path | None = None) -> int:
    from google.cloud import bigquery

    items = list(rendered(files, project))
    estimates, over, failed = estimate_all(client, items, max_gb)
    total = sum(estimates.values()) / 1e9
    log.info("total estimate: %.3f GB over %d query parts", total, len(items))
    if failed:
        return EXIT_BAD_SQL
    if over:
        return EXIT_OVER_BUDGET
    if estimate_only:
        return EXIT_OK

    results, bytes_by_part = {}, {}
    for qf, part, sql in items:
        job = client.query(sql, job_config=bigquery.QueryJobConfig(
            maximum_bytes_billed=int(max_gb * 1e9)))
        rows = [dict(r.items()) for r in job.result()]
        key = (qf.qid, part)
        results[key] = rows
        bytes_by_part[key] = {"estimated": estimates[key],
                              "processed": getattr(job, "total_bytes_processed", None)}
        write_csv(out / csv_name(qf, part), rows)
        log.info("ran %s/%s: %d rows", qf.qid, part, len(rows))

    run_at = dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    # Keep byte counts (and run times) of parts not re-run this time.
    meta_path = out / "run_meta.json"
    prev = json.loads(meta_path.read_text(encoding="utf-8")) if meta_path.exists() else {}
    prev_bytes = prev.get("bytes", {})
    ran_at = prev.get("ran_at", {})
    for (q, p) in bytes_by_part:
        ran_at[f"{q}/{p}"] = run_at
    for k, v in prev_bytes.items():
        q, p = k.split("/", 1)
        bytes_by_part.setdefault((q, p), v)
    # RESULTS.md always describes every query file; parts not run this time are
    # read back from their existing CSVs so a partial --only run keeps the rest.
    all_files = bq_utils.load_query_dir(sql_dir) if sql_dir else files
    for qf in all_files:
        for part, _ in qf.parts:
            key = (qf.qid, part)
            p = out / csv_name(qf, part)
            if key not in results and p.exists():
                with p.open(encoding="utf-8") as f:
                    results[key] = list(csv.DictReader(f))
    (out / "RESULTS.md").write_text(
        build_results_md(all_files, results, bytes_by_part, project, run_at), encoding="utf-8")
    meta_path.write_text(json.dumps({
        "last_run_at": run_at, "project": project, "max_gb": max_gb,
        "ran_at": dict(sorted(ran_at.items())),
        "bytes": {f"{q}/{p}": v for (q, p), v in sorted(bytes_by_part.items())},
    }, indent=2, default=str), encoding="utf-8")
    log.info("wrote %s", out)
    return EXIT_OK


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--project", required=True)
    ap.add_argument("--out", type=Path, default=OUT_DIR)
    ap.add_argument("--sql-dir", type=Path, default=SQL_DIR)
    ap.add_argument("--only", nargs="*", help="file prefixes to run, e.g. 05 07")
    ap.add_argument("--max-gb", type=float, default=5.0,
                    help="stop if the dry run estimates more than this per query part")
    ap.add_argument("--estimate-only", action="store_true", help="dry-run only, print costs")
    ap.add_argument("--print-only", action="store_true", help="print the SQL; no GCP call")
    args = ap.parse_args(argv)
    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(message)s")

    files = bq_utils.load_query_dir(args.sql_dir, args.only)
    if args.print_only:
        for qf, part, sql in rendered(files, args.project):
            print(f"-- ===== {qf.qid} / {part} =====\n{sql}\n")
        return EXIT_OK

    from google.cloud import bigquery
    client = bigquery.Client(project=args.project)
    return run(client, args.project, files, args.out, args.max_gb, args.estimate_only,
               sql_dir=args.sql_dir)


if __name__ == "__main__":
    sys.exit(main())
