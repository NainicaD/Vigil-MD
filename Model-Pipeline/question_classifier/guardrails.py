"""Medical-advice guardrails around the question classifier.

Strict rule: the chatbot never gives medical advice and never judges whether a device is
safe. A model alone cannot guarantee that, so out_of_scope is decided in layers:

  1. Rule backstop (this file): fixed patterns mark a question out_of_scope even when the
     model does not. Tuned for recall: a false alarm costs a refusal, a miss could cost
     a patient acting on a chatbot answer.
  2. Classifier: out_of_scope threshold set for high recall on validation (train.py).
  3. Routing (route()): out_of_scope overrides every other label. With the default
     "strict" policy no query runs and the user gets REFUSAL, fixed text written here,
     never generated by a model.
  4. The chatbot's output gate (teammate's design) blocks advice wording in drafts.

Change these patterns only together with the guardrail test slice in the evaluation.
"""
from __future__ import annotations

import re

from .labels import OUT_OF_SCOPE

REFUSAL = (
    "I can't give medical advice or judge whether a device is safe for you. "
    "Please talk to your doctor or another qualified health professional about your "
    "situation. If you think a device has harmed someone, you can report it to the FDA "
    "through MedWatch. I can share what FDA reports and recalls say about a device, for "
    "example how many reports it has or whether it has been recalled."
)

# Each pattern is matched against the lower-cased question.
ADVICE_PATTERNS: tuple[tuple[str, str], ...] = (
    ("should_i",        r"\bshould (i|we|my|he|she|they|you)\b"),
    ("what_to_do",      r"\bwhat (do|should|can) (i|we) do\b"),
    ("is_it_safe",      r"\b(is|are|was) (it|this|that|they|my\b.*?|the\b.*?) "
                        r"(safe|dangerous|risky|ok|okay|reliable)\b"),
    ("safe_to",         r"\bsafe (to|for)\b"),
    # Any safety judgement word: the bot reports what reports say, it never judges safety
    ("safety_judgement", r"\b(safe|unsafe|dangerous|risky|harmful)\b"),
    ("safer_better",    r"\b(safer|safest|better|best|most reliable)\b.*\b(pump|device|"
                        r"implant|monitor|valve|stent|one|option|brand|choice)\b"),
    ("best_choice",     r"\b(best|safest|safer|better|most reliable)\b.{0,40}"
                        r"\b(on the market|to (buy|use|get|choose|pick)|for (me|my|a patient|"
                        r"patients|kids|children|our))\b"
                        r"|\b(which|what)(\s+\w+){0,3}\s+(is|are) (the )?(best|safest|safer|"
                        r"better|most reliable)\b"),
    ("stop_switch",     r"\b(stop|keep|start|continue|switch|quit|remove|replace) "
                        r"(using|taking|wearing|my)\b"),
    ("dosing",          r"\b(dose|dosage|dosing|how much insulin|how many units)\b"),
    ("symptoms",        r"\b(symptom|symptoms|diagnos\w*|i feel|i have (a |an )?(pain|rash|"
                        r"fever|infection))\b"),
    # Asking the bot for a recommendation, not "what did the recall recommend"
    ("recommend",       r"\b(do|would|can|could) you (recommend|suggest|advise)\b"
                        r"|\brecommend (me|a|an|which|the best)\b|\bmedical advice\b"
                        r"|\b(your|any) advice\b"),
    ("can_i",           r"\bcan i (still |keep |safely )?(use|wear|take|get)\b"),
    ("worried",         r"\b(worried|scared|afraid|anxious)\b"),
)
_COMPILED = tuple((name, re.compile(pat)) for name, pat in ADVICE_PATTERNS)

POLICIES = ("strict", "facts_with_refusal")


def rule_hits(question: str) -> list[str]:
    """Names of the advice patterns that match the question."""
    q = question.lower()
    return [name for name, rx in _COMPILED if rx.search(q)]


def route(labels: list[str], question: str, policy: str = "strict") -> dict:
    """Combine model labels with the rule backstop and decide what the chatbot does.

    Returns {"labels", "rule_hits", "out_of_scope", "run_queries", "refusal"}:
      strict              out_of_scope → refuse, run no query
      facts_with_refusal  out_of_scope → refuse the advice part, still run the factual
                          labels' queries (the answer must start with REFUSAL)
    No label at all (low confidence) → run nothing, ask the user to rephrase.
    """
    if policy not in POLICIES:
        raise ValueError(f"policy must be one of {POLICIES}")
    hits = rule_hits(question)
    final = sorted(set(labels) | ({OUT_OF_SCOPE} if hits else set()))
    oos = OUT_OF_SCOPE in final
    factual = [lbl for lbl in final if lbl != OUT_OF_SCOPE]
    if oos and policy == "strict":
        run = []
    else:
        run = factual
    return {"labels": final, "rule_hits": hits, "out_of_scope": oos,
            "run_queries": run, "refusal": REFUSAL if oos else None}
